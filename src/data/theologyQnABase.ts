/**
 * Generates an articulate, deeply evangelical Amharic theological answer
 * by matching knowledge concepts or applying systematic biblical exegesis.
 */
export function generateClientTheologyAnswer(question: string, context?: string): string {
  const cleanQ = question.toLowerCase().trim();

  // 1. Direct match with curated topics
  for (const topic of PREDEFINED_THEOLOGY_TOPICS) {
    if (topic.keywords.some(k => cleanQ.includes(k.toLowerCase()))) {
      let finalAns = topic.answer;
      if (context && context.trim().length > 0) {
        finalAns += `\n\n---\n**📌 የተጠቀሰው የመጽሐፍ ቅዱስ አውድ፦** ${context}`;
      }
      return finalAns;
    }
  }

  // 2. Check 5 Solas match
  for (const sola of FIVE_SOLAS) {
    if (cleanQ.includes(sola.latin.toLowerCase()) || cleanQ.includes(sola.amharic.toLowerCase()) || cleanQ.includes(sola.english.toLowerCase())) {
      return `### 🏛️ ${sola.latin} (${sola.amharic} / ${sola.english})

**ዋና መሪ ቃል፦**
> «${sola.motto}»

**ሥነ-መለኮታዊ ማብራሪያ፦**
${sola.summaryAm}

**ዋና የመጽሐፍ ቅዱስ ማስረጃ፦**
- **ጥቅስ፦** ${sola.scriptureRef}
- *«${sola.keyScriptureAm}»*

**የተሐድሶ ታሪካዊና አስተምህሮታዊ ፋይዳ፦**
${sola.theologicalImpactAm}
${context ? `\n\n**📌 ተያያዥ አውድ፦** ${context}` : ''}`;
    }
  }

  // 3. Check Topical Studies match
  for (const study of TOPICAL_STUDIES) {
    if (cleanQ.includes(study.id.toLowerCase()) || cleanQ.includes(study.titleAm.toLowerCase()) || cleanQ.includes(study.titleEn.toLowerCase())) {
      const readings = study.scriptureReadings.map(r => `- **${r.ref}**: «${r.textAm}»\n  *${r.analysisAm}*`).join('\n\n');
      return `### 📚 ${study.titleAm}

**የአስተምህሮው ማጠቃለያ፦**
${study.coreDoctrineAm}

**ዋና ዋና የመጽሐፍ ቅዱስ ክፍሎችና ትንታኔዎች፦**
${readings}
${context ? `\n\n**📌 ተያያዥ አውድ፦** ${context}` : ''}`;
    }
  }

  // 4. Dynamic Christocentric Systematic Theology Generator
  return `### 📖 መጽሐፍ ቅዱሳዊና ሥነ-መለኮታዊ ምላሽ (Evangelical Biblical Response)

**የቀረበው ጥያቄ፦** «${question}»

በወንጌላዊ ፕሮቴስታንት አስተምህሮ እና በቅዱሳት መጻሕፍት የበላይ ሥልጣን (*Sola Scriptura*) መሠረት የሚከተሉት መሠረታዊ የወንጌል እውነቶች ይብራራሉ፦

1. **የቅዱሳት መጻሕፍት የበላይነት (2ኛ ጢሞቴዎስ 3:16-17, መዝሙር 119:105)**
   - መጽሐፍ ቅዱስ የእግዚአብሔር እስትንፋስ ያለበት፣ የማይሳሳትና ለድነት እንዲሁም ለእውነተኛ ክርስቲያናዊ ሕይወት በቂ የሆነ ብቸኛው የእምነትና የኑሮ መመሪያችን ነው።

2. **የክርስቶስ የማዳን ሥራና ጸጋ (ኤፌሶን 2:8-9, ሮሜ 8:1-2)**
   - በኢየሱስ ክርስቶስ የመስቀል ቤዛነትና በትንሣኤው ኃይል አማካኝነት ወደ አብ የምንቀርብበት ነጻ የጸጋ መንገድ ተከፍቶልናል። ክርስቶስ ብቸኛው አማላጅ፣ ሊቀ ካህናትና መድኃኒት ነው (1ኛ ጢሞቴዎስ 2:5, የሐዋርያት ሥራ 4:12)።

3. **በመንፈስ ቅዱስ መመራትና የሕይወት ቅድስና (ገላትያ 5:22-25, ሮሜ 12:1-2)**
   - አማኝ በጸሎት፣ በቃሉ ማሰላሰል እና በመንፈስ ቅዱስ ኅብረት የእግዚአብሔርን ፈቃድ እያወቀ በቅድስና፣ በፍቅርና በታማኝነት እንዲመላለስ ተጠርቷል።

${context ? `**📌 የተጠቀሰው የመጽሐፍ ቅዱስ አውድ፦** ${context}\n\n` : ''}💡 *ለተጨማሪ ዝርዝር ማብራሪያ በመተግበሪያው ውስጥ የሚገኙትን **የአምስቱ ሶላዎች (Five Solas)** እና **የጥልቅ ቲኦሎጂ ጥናት** ክፍሎችን መመልከት ይችላሉ።*`;
}
